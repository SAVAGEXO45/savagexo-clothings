<?php

namespace App\Services;

use App\Models\Order;
use App\Models\Payment;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Str;

class PaymentService
{
    /**
     * Initialize a payment record for Paystack, Flutterwave, or Cash on Delivery.
     * Never stores any card numbers, CVV, or PIN.
     */
    public function initializePayment(Order $order, string $gateway): Payment
    {
        $prefix = match ($gateway) {
            'paystack' => 'SXO-PSK-',
            'flutterwave' => 'SXO-FLW-',
            default => 'SXO-COD-',
        };

        $reference = $prefix . strtoupper(Str::random(10)) . '-' . $order->id;

        return Payment::create([
            'order_id' => $order->id,
            'user_id' => $order->user_id,
            'gateway' => $gateway,
            'transaction_reference' => $reference,
            'amount' => $order->total_amount,
            'currency' => 'NGN',
            'status' => 'pending',
            'channel' => $gateway === 'cod' ? 'cash_on_delivery' : 'card_or_transfer',
            'gateway_response' => [
                'initialized_at' => now()->toIso8601String(),
                'environment' => config('app.env'),
            ],
        ]);
    }

    /**
     * Verify a transaction securely on the backend.
     * Supports live Paystack / Flutterwave verification when keys are live, and
     * deterministic sandbox signature verification in local/testing environments.
     */
    public function verifyTransaction(Payment $payment, array $payload = []): array
    {
        if ($payment->status === 'success') {
            return [
                'verified' => true,
                'message' => 'Payment already verified.',
                'payment' => $payment,
            ];
        }

        $gateway = $payment->gateway;
        $secretKey = $gateway === 'paystack'
            ? config('services.paystack.secret_key')
            : config('services.flutterwave.secret_key');

        $isSandbox = str_contains((string) $secretKey, 'test') || app()->environment(['local', 'testing']);

        $verified = false;
        $gatewayRef = $payload['gateway_reference'] ?? strtoupper($gateway . '-REF-' . Str::random(8));
        $channel = $payload['channel'] ?? 'card';
        $responseMeta = [];

        if (! $isSandbox && $gateway === 'paystack') {
            try {
                $response = Http::withToken($secretKey)
                    ->timeout(10)
                    ->get(config('services.paystack.payment_url') . '/transaction/verify/' . urlencode($payment->transaction_reference));

                $data = $response->json();
                if ($response->successful() && ($data['data']['status'] ?? '') === 'success') {
                    $paidKobo = (int) ($data['data']['amount'] ?? 0);
                    $expectedKobo = (int) round((float) $payment->amount * 100);
                    $verified = $paidKobo >= $expectedKobo;
                    $gatewayRef = (string) ($data['data']['id'] ?? $gatewayRef);
                    $channel = (string) ($data['data']['channel'] ?? 'card');
                    $responseMeta = $data['data'] ?? [];
                }
            } catch (\Throwable $e) {
                $responseMeta = ['error' => $e->getMessage()];
            }
        } elseif (! $isSandbox && $gateway === 'flutterwave') {
            try {
                $txId = $payload['transaction_id'] ?? $payment->transaction_reference;
                $response = Http::withToken($secretKey)
                    ->timeout(10)
                    ->get("https://api.flutterwave.com/v3/transactions/{$txId}/verify");

                $data = $response->json();
                if ($response->successful() && ($data['data']['status'] ?? '') === 'successful') {
                    $paidAmount = (float) ($data['data']['amount'] ?? 0);
                    $verified = $paidAmount >= (float) $payment->amount;
                    $gatewayRef = (string) ($data['data']['flw_ref'] ?? $gatewayRef);
                    $channel = (string) ($data['data']['payment_type'] ?? 'card');
                    $responseMeta = $data['data'] ?? [];
                }
            } catch (\Throwable $e) {
                $responseMeta = ['error' => $e->getMessage()];
            }
        } else {
            // Sandbox / Test mode verification:
            // Verifies HMAC token generated by backend for the transaction reference
            $expectedSignature = hash_hmac('sha256', $payment->transaction_reference . '|' . number_format((float) $payment->amount, 2, '.', ''), config('app.key'));
            $providedSignature = $payload['signature'] ?? '';
            $simulatedOutcome = $payload['outcome'] ?? 'success';

            if (hash_equals($expectedSignature, $providedSignature) && $simulatedOutcome === 'success') {
                $verified = true;
                $responseMeta = [
                    'mode' => 'sandbox_verified',
                    'gateway' => $gateway,
                    'reference' => $payment->transaction_reference,
                    'gateway_reference' => $gatewayRef,
                    'amount_ngn' => (float) $payment->amount,
                    'channel' => $channel,
                    'verified_by' => 'SAVAGEXO Backend Verification Engine',
                ];
            } else {
                $responseMeta = [
                    'mode' => 'sandbox_declined',
                    'reason' => $simulatedOutcome === 'failed' ? 'Customer cancelled or simulated failure' : 'Invalid signature',
                ];
            }
        }

        if ($verified) {
            $payment->update([
                'status' => 'success',
                'gateway_reference' => $gatewayRef,
                'channel' => $channel,
                'gateway_response' => $responseMeta,
                'verified_at' => now(),
            ]);

            $payment->order->update([
                'payment_status' => 'paid',
                'order_status' => $payment->order->order_status === 'pending' ? 'confirmed' : $payment->order->order_status,
                'paid_at' => now(),
            ]);

            return [
                'verified' => true,
                'message' => 'Payment verified',
                'payment' => $payment->fresh(),
            ];
        }

        $payment->update([
            'status' => 'failed',
            'gateway_response' => $responseMeta,
        ]);

        $payment->order->update([
            'payment_status' => 'failed',
        ]);

        return [
            'verified' => false,
            'message' => 'Payment verification failed or was cancelled.',
            'payment' => $payment->fresh(),
        ];
    }

    public function generateSandboxSignature(Payment $payment): string
    {
        return hash_hmac(
            'sha256',
            $payment->transaction_reference . '|' . number_format((float) $payment->amount, 2, '.', ''),
            config('app.key')
        );
    }
}
